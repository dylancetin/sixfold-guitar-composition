// Reproduce the small, offline guitar bank from the pinned alphaTab dependency.
// This is sample extraction, not a general SoundFont renderer/importer.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const font = await readFile(fileURLToPath(new URL('../node_modules/@coderline/alphatab/dist/soundfont/sonivox.sf2', import.meta.url)));
const chunks = new Map<string, Buffer>();
function readChunks(start: number, end: number) {
  for (let offset = start; offset + 8 <= end;) {
    const id = font.toString('ascii', offset, offset + 4), size = font.readUInt32LE(offset + 4), data = offset + 8;
    if (data + size > end) throw new Error('Invalid SoundFont chunk');
    if (id === 'LIST') readChunks(data + 4, data + size);
    else chunks.set(id, font.subarray(data, data + size));
    offset = data + size + (size % 2);
  }
}
if (font.toString('ascii', 0, 4) !== 'RIFF' || font.toString('ascii', 8, 12) !== 'sfbk') throw new Error('Expected SF2');
readChunks(12, font.length);
const chunk = (id: string) => { const data = chunks.get(id); if (!data) throw new Error(`Missing ${id}`); return data; };
const phdr = chunk('phdr'), pbag = chunk('pbag'), pgen = chunk('pgen'), inst = chunk('inst');
const ibag = chunk('ibag'), igen = chunk('igen'), shdr = chunk('shdr'), pcm = chunk('smpl');
let instrument = -1;
for (let offset = 0; offset + 38 < phdr.length; offset += 38) {
  if (phdr.readUInt16LE(offset + 20) !== 25 || phdr.readUInt16LE(offset + 22) !== 0) continue;
  const first = phdr.readUInt16LE(offset + 24), last = phdr.readUInt16LE(offset + 38 + 24);
  for (let bag = first; bag < last; bag++) {
    for (let gen = pbag.readUInt16LE(bag * 4); gen < pbag.readUInt16LE((bag + 1) * 4); gen++) {
      if (pgen.readUInt16LE(gen * 4) === 41) instrument = pgen.readUInt16LE(gen * 4 + 2);
    }
  }
}
if (instrument < 0) throw new Error('Missing steel-string acoustic guitar preset');
const zones = [];
for (let bag = inst.readUInt16LE(instrument * 22 + 20); bag < inst.readUInt16LE((instrument + 1) * 22 + 20); bag++) {
  const generators = new Map<number, number>();
  for (let gen = ibag.readUInt16LE(bag * 4); gen < ibag.readUInt16LE((bag + 1) * 4); gen++) generators.set(igen.readUInt16LE(gen * 4), igen.readUInt16LE(gen * 4 + 2));
  const sampleId = generators.get(53);
  if (sampleId === undefined) continue; // Instrument-global envelope is replaced by our preview envelope.
  const range = generators.get(43), offset = sampleId * 46;
  if (range === undefined || generators.get(54) !== 1 || shdr.readUInt16LE(offset + 44) !== 1) throw new Error('Unexpected guitar sample zone');
  const start = shdr.readUInt32LE(offset + 20), end = shdr.readUInt32LE(offset + 24);
  zones.push({
    low: range & 255, high: range >> 8, root: shdr[offset + 40]!, correction: shdr.readInt8(offset + 41),
    sampleRate: shdr.readUInt32LE(offset + 36), loopStart: shdr.readUInt32LE(offset + 28) - start, loopEnd: shdr.readUInt32LE(offset + 32) - start,
    attenuation: generators.get(48) ?? 0, pcm16: pcm.subarray(start * 2, end * 2).toString('base64'),
  });
}
if (zones.length !== 5 || zones[0]!.low !== 0 || zones.at(-1)!.high !== 127 || zones.some((zone, i) => zone.loopStart < 0 || zone.loopEnd <= zone.loopStart || (i > 0 && zones[i - 1]!.high + 1 !== zone.low))) throw new Error('Unexpected guitar bank layout');
const digest = createHash('sha256').update(font).digest('hex');
const output = `// Generated by bun scripts/extract-guitar-samples.ts; do not hand-edit.\n// SONiVOX EAS, Copyright (c) 2004-2006 Sonic Network Inc., Apache-2.0.\n// Extracted PCM only; preview envelopes are modified. See GUITAR-SAMPLES.md.\n// Source SF2 SHA-256: ${digest}\nexport const guitarSamples = ${JSON.stringify(zones, null, 2)};\n`;
await writeFile(fileURLToPath(new URL('../src/adapters/guitar-samples.ts', import.meta.url)), output);
console.log(`Extracted ${zones.length} acoustic guitar zones (${zones.reduce((sum, zone) => sum + Buffer.from(zone.pcm16, 'base64').length, 0)} PCM bytes).`);
